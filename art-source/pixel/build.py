"""Regenerate the v2 pixel assets.

    python3 art-source/pixel/build.py            # atlas + font
    python3 art-source/pixel/build.py --font     # font only (after changing any text)

Writes:
    game/assets/pixel/atlas.png   every sprite (ships at 7 sizes, siren, clouds, island, foam, icons)
    game/data/sprites.js          Siren.SPRITES = { name: [x, y, w, h] }, Siren.SIREN_META
    game/assets/pixel/font.png    1-bit bitmap font (white), only the characters the game uses
    game/data/font.js             Siren.FONT = { h, g: { char: [x, y, advance] } }

Needs: Python 3 with numpy, Pillow, cairosvg; Node (to read the game's text data).
The font is Fusion Pixel 12px proportional (SIL OFL 1.1, see font/OFL.txt).
"""
import json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
GAME = os.path.join(ROOT, "game")
sys.path.insert(0, os.path.join(HERE, "lib"))

from PIL import Image, ImageDraw, ImageFont  # noqa: E402
import pix  # noqa: E402
import scene  # noqa: E402

OUT_IMG = os.path.join(GAME, "assets", "pixel")
OUT_DATA = os.path.join(GAME, "data")
os.makedirs(OUT_IMG, exist_ok=True)

WHITE = (255, 255, 255, 255)

# ------------------------------------------------------------------ icons (white, tinted at runtime)
MONO = {
    "i_back": ["...KK", "..KK.", ".KK..", "KK...", ".KK..", "..KK.", "...KK"],
    "i_pause": ["KK.KK", "KK.KK", "KK.KK", "KK.KK", "KK.KK", "KK.KK", "KK.KK"],
    "i_check": ["......KK", ".....KK.", "KK..KK..", ".KKKK...", "..KK....", "........"],
    "i_dice": [".KKKKKKK.", "K.......K", "K.K...K.K", "K.......K", "K...K...K", "K.......K", "K.K...K.K", "K.......K", ".KKKKKKK."],
    "i_next": ["KK...", ".KK..", "..KK.", "...KK", "..KK.", ".KK..", "KK..."],
    "i_x": ["KK...KK", ".KK.KK.", "..KKK..", ".KK.KK.", "KK...KK"],
}


def sprites():
    items = {}
    for face in ("calm", "sing", "listen"):
        items["siren_" + face] = Image.open(os.path.join(HERE, "siren", face + ".png")).convert("RGBA")

    ships = json.load(open(os.path.join(HERE, "ships-svg.json"), encoding="utf-8"))
    for sh in ships:
        svg, key = sh["svg"], sh["key"]
        items["big_" + key] = pix.soften_foam(pix.pixelize(svg, 120, 98, 4, out_thresh=0.45), 75)
        items["b88_" + key] = pix.soften_foam(pix.pixelize(svg, 88, 72, 5, out_thresh=0.4), 55)
        items["ship_" + key] = pix.soften_foam(pix.pixelize(svg, 64, 52, 5, out_thresh=0.3), 40)
        items["s48_" + key] = pix.soften_foam(pix.pixelize(svg, 48, 39, 6, out_thresh=0.3), 30)
        for w in (32, 20, 12):
            h = round(w * 260 / 320)
            k = max(4, round(320 / w / 1.0) // 2)
            items["s%d_%s" % (w, key)] = pix.pixelize(svg, w, h, min(k, 16), out_thresh=0.34)

    isl = Image.new("RGBA", (60, 40), (0, 0, 0, 0))
    scene.island(isl, 6, 36)
    items["island"] = pix.trim(isl)
    for i, w in enumerate((40, 28, 20)):
        c = Image.new("RGBA", (w + 2, w), (0, 0, 0, 0))
        scene.cloud(c, 0, 0, w)
        items["cloud%d" % i] = pix.trim(c)
    items["foam_a"] = pix.foam_strip(84, 5)
    items["foam_b"] = pix.foam_strip(84, 7)

    for name, rows in (("i_mic", pix.ICON_MIC), ("i_note", pix.ICON_NOTE), ("i_note2", pix.ICON_NOTE2),
                       ("i_heart", pix.ICON_HEART), ("i_book", pix.ICON_BOOK)):
        items[name] = pix.icon(rows, {"R": pix.rgb("#ff5d7a")} if name == "i_heart" else None)
    for name, rows in MONO.items():
        items[name] = pix.from_map(rows, {"K": WHITE})

    # shelf pack, tallest first
    names = sorted(items, key=lambda n: (-items[n].height, n))
    AW = 640
    x = y = rowh = 0
    rects = {}
    for n in names:
        im = items[n]
        if x + im.width + 1 > AW:
            x = 0
            y += rowh + 1
            rowh = 0
        rects[n] = [x, y, im.width, im.height]
        x += im.width + 1
        rowh = max(rowh, im.height)
    atlas = Image.new("RGBA", (AW, y + rowh + 1), (0, 0, 0, 0))
    for n in names:
        atlas.alpha_composite(items[n], tuple(rects[n][:2]))
    atlas.save(os.path.join(OUT_IMG, "atlas.png"), optimize=True)

    meta = {"edge": 34, "w": items["siren_calm"].width, "h": items["siren_calm"].height}
    js = ("/* generated by art-source/pixel/build.py — do not edit */\n"
          "(function (g) {\n  var Siren = g.Siren = g.Siren || {};\n"
          "  Siren.SPRITES = " + json.dumps(rects, separators=(",", ":"), sort_keys=True) + ";\n"
          "  Siren.SIREN_META = " + json.dumps(meta) + ";\n"
          "})(typeof window !== 'undefined' ? window : (typeof self !== 'undefined' ? self : {}));\n")
    open(os.path.join(OUT_DATA, "sprites.js"), "w", encoding="utf-8").write(js)
    print("atlas", atlas.size, os.path.getsize(os.path.join(OUT_IMG, "atlas.png")), "bytes,", len(rects), "sprites")


# ------------------------------------------------------------------ font
def strip_comments(src):
    src = re.sub(r"/\*[\s\S]*?\*/", " ", src)
    return re.sub(r"(^|[^:])//[^\n]*", r"\1", src)


def used_chars():
    data_files = ["songs.js", "ships.js", "i18n.js", "changelog.js"]
    script = (
        "const vm=require('vm'),fs=require('fs'),path=require('path');"
        "const sb={};sb.window=sb;vm.createContext(sb);"
        "for(const f of process.argv.slice(1))vm.runInContext(fs.readFileSync(f,'utf8'),sb);"
        "const out=[];(function walk(v){if(typeof v==='string')out.push(v);else if(v&&typeof v==='object')for(const k in v)if(k!=='origin')walk(v[k]);})"
        "([sb.Siren.SONGS,sb.Siren.SHIPS,sb.Siren.I18N,sb.Siren.LANGS,sb.Siren.CHANGELOG]);"
        "process.stdout.write(out.join('\\n'));"
    )
    text = subprocess.check_output(["node", "-e", script] + [os.path.join(OUT_DATA, f) for f in data_files]).decode("utf-8")
    ui_dir = os.path.join(GAME, "js", "ui")
    if os.path.isdir(ui_dir):
        for f in sorted(os.listdir(ui_dir)):
            if f.endswith(".js"):
                text += strip_comments(open(os.path.join(ui_dir, f), encoding="utf-8").read())
    chars = set(chr(c) for c in range(32, 127))
    chars |= set(ch for ch in text if ord(ch) > 127 and ch not in "\n\r\t")
    return sorted(chars)


def font():
    chars = used_chars()
    f = ImageFont.truetype(os.path.join(HERE, "font", "fusion-pixel-12px-proportional-zh_hans.ttf"), 12)
    asc, desc = f.getmetrics()
    cells = []
    top, bot = 99, 0
    missing = []
    for ch in chars:
        adv = max(1, int(round(f.getlength(ch))))
        im = Image.new("L", (adv + 2, asc + desc), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = "1"
        d.text((0, 0), ch, font=f, fill=255)
        bb = im.getbbox()
        if bb:
            top, bot = min(top, bb[1]), max(bot, bb[3])
        elif ch != " ":
            missing.append(ch)
        cells.append((ch, adv, im))
    top = max(0, top - 1)
    h = bot - top
    AW = 512
    x = y = 0
    g = {}
    for ch, adv, im in cells:
        if x + adv + 1 > AW:
            x = 0
            y += h + 1
        g[ch] = [x, y, adv]
        x += adv + 1
    atlas = Image.new("RGBA", (AW, y + h + 1), (0, 0, 0, 0))
    for ch, adv, im in cells:
        gx, gy, _ = g[ch]
        crop = im.crop((0, top, adv, top + h))
        white = Image.new("RGBA", crop.size, WHITE)
        white.putalpha(crop.point(lambda v: 255 if v > 127 else 0))
        atlas.alpha_composite(white, (gx, gy))
    atlas.save(os.path.join(OUT_IMG, "font.png"), optimize=True)
    js = ("/* generated by art-source/pixel/build.py — do not edit */\n"
          "(function (g) {\n  var Siren = g.Siren = g.Siren || {};\n"
          "  Siren.FONT = " + json.dumps({"h": h, "g": g}, ensure_ascii=False, separators=(",", ":")) + ";\n"
          "})(typeof window !== 'undefined' ? window : (typeof self !== 'undefined' ? self : {}));\n")
    open(os.path.join(OUT_DATA, "font.js"), "w", encoding="utf-8").write(js)
    print("font", len(chars), "chars, cell h", h, ",", os.path.getsize(os.path.join(OUT_IMG, "font.png")), "bytes")
    if missing:
        print("WARNING: glyphs missing from the font:", "".join(missing))


if __name__ == "__main__":
    if "--font" not in sys.argv:
        sprites()
    font()
